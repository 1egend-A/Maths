function cfg = p0_config()
% P0_CONFIG  全局参数与口径的【唯一真源】
% 规则：任何人改参数/改口径，只改这一个文件，并在下面签注日期与理由。
% 依据：题目附录 1 + 队内当面定死的口径。
%
% ============================================================
% ✅  本文件口径 1–7 已全部定死（2026-09-13）。
%
%   口径 1、4、5 此前已定；口径 2 / 3 / 6 / 7 原为【占位值】，
%   经队内三人当面确认，于 2026-09-13 正式追认。
%
%   其中口径 2 / 3 / 7 追认后取值与原占位值【完全一致】；
%   口径 6 由 'positional' 改为新选项 'corrected_labels'（语义见下），
%   该改动【只改标签、不改任何数值】，既往结果同样无需重算。
%
%   因此：现有全部计算结果均可直接写进论文并作为提交依据。
%
%   已定口径：1（效率计量侧）、2（日末 SOC）、3（调整量结算粒度）、
%   4（时段归属）、5（附件3 区间归属，属实证标定而非选择，有 21876
%   样本扫描支撑）、6（附件5 模板填充规则）、7（Q2/Q3 信息集）。
% ============================================================

% ==================== 储能参数（附录 1）====================
cfg.eta   = 0.90;    % 单向充放电效率
cfg.S_cap = 12000;   % 容量 kWh
cfg.S_min = 1200;    % SOC 下限 kWh
cfg.S_max = 10800;   % SOC 上限 kWh
cfg.S0    = 6000;    % 2025-01-01 0:00 初始 SOC kWh
cfg.P_max = 5000;    % 最大充电/放电功率 kW
cfg.dt    = 1/6;     % 时段长度 小时（10 分钟）

% ==================== 口径 1：效率计量侧 ⚠️ ====================
% 'ac' : c,d 都是【交流侧】计量（电表在电网/负载侧）
%          功率平衡 g + d = L + c
%          SOC 增量  (c*eta - d/eta)*dt
% 'dc' : c,d 都是【直流侧】计量（电池侧）
%          功率平衡 g + d*eta = L + c/eta
%          SOC 增量  (c - d)*dt
% 两者都能自洽，但【必须二选一并全文统一】，混用会算错费用且不报错。
cfg.effConv = 'ac';

% ==================== 口径 2：日末 SOC ====================
% ✅ 2026-09-13 定死：'close' + cfg.S_end = 6000（日末回到当日起点）。
%    论文按此执行：问题一按题设要求首尾相等；问题二至四采用每天首尾
%    6000 kWh 的【附加保守政策】，论文中已显式声明不宣称这是题目允许的
%    所有跨日策略中的全局最优。
%    追溯：本值原为占位值，队内于 2026-09-13 当面追认，取值未变，
%    故既往 Q1–Q4 结果无需重算。
%
% 'free'  每个优化日不约束日末 SOC（仅受 [S_min,S_max] 约束）
% 'close' 日末回到当日起点
% 'fixed' 日末固定为 cfg.S_end
% 参考实测（g0_feb01.m；该实验用 'close' 与 'free' 对比，结论不依赖本条是否追认）：
%    'free' 是退化解——第一天就把电池压到下限 1200 并永远趴着，丧失后续
%    套利能力，1 月反而多花约 5,812 元；且会让 2025-02-01 起始 SOC = 1200
%    而非 6000，Q2/Q3 从错误状态起步。
% 若采用 'close' 或 'fixed'，两者在本题数值上等价（均得 2/1 SOC = 6000）。
cfg.termPolicy = 'close';      % 2026-09-13 定死
cfg.S_end      = 6000;         % 2026-09-13 定死

% ==================== 口径 3：调整量结算粒度（Q3 用）====================
% ✅ 2026-09-13 定死：'slot'（逐 10 分钟比计划）。
% 'slot' 逐 10 分钟比计划；'day' 按全天总量比计划
% 这一条直接决定 Q3 的偏差量怎么算，进而决定 0.5×/1.5× 非对称罚则的金额。
% 论文按 'slot' 执行（式 (19)(20)）：取消部分退还原计划费用、再按 50% 支付
% 违约费；增加部分按 1.5 倍结算。
% 代价已量化存档：'day' 口径下 Q3 金额与 'slot' 相差 23.161%（旧版对比实验），
% 两者不可混用、不可拼接。队内于 2026-09-13 当面选定 'slot'，取值未变，
% 故既往 Q3 结果无需重算。
cfg.adjGranularity = 'slot';   % 2026-09-13 定死

% ==================== 口径 4：时段归属 ====================
% 第 i 个数据点 = 区间 (t_{i-1}, t_i] 的右端点，区间是【结算/执行】的单位。
% 即标签 '00:10' 表示 00:00-00:10 这 10 分钟。
cfg.slotConvention = 'right-endpoint';
cfg.slotNote = '标签 T 代表区间 (T-dt, T]，执行与结算都以该区间为单位';

% ==================== 口径 5：附件3 预报区间归属 ⚠️ 实证标定 ====================
% 附件3 列名是「预报1小时…预报24小时」，题面未说明起点。calib_fc_offset.m
% 用附件2 全年实际光伏做反向标定（合并 RMSE 扫描 21876 个样本）：
%     o=-1: 2830.94  |  o=0: 1797.08  |  o=+1: 763.78 ← 最优  |  o=+2: 919.16
% 最小值孤立地落在 o=+1，四个发布时刻各自 15/15 个步长全部支持该偏移。
% 内部一致性铁证：0:00 的 k=5、12:00 的 k=17、18:00 的 k=11 按此规则
% 全部落到同一钟点 04:00-05:00，三处 RMSE 均为 1.4 kW。
%
% 语义：【预报k小时 = 发布时刻起算的第 k 个小时】
%       区间 [发布时刻+(k-1)h, 发布时刻+k·h)，k=1..24 铺满发布后 24 小时。
%       6:00 发布的「预报1小时」= 06:00-07:00；「预报18小时」= 23:00-24:00；
%       「预报19小时」起跨入次日。
%
% 索引公式（全局小时索引 t，0 起算小时数 h0 从 0 数到 23）：
%       t  = (d-1)*24 + issueHour_j + k - 1 + cfg.fcOffset
%       h0 = mod(issueHour_j + k - 1, 24),  跨天标志 = (issueHour_j + k - 1 >= 24)
cfg.fcOffset   = +1;
cfg.fcIssHours = [0, 6, 12, 18];      % 附件3 四个发布时刻（小时）
cfg.fcRuleNote = '预报k小时 = [发布时刻+(k-1)h, 发布时刻+k*h)，实证标定于 calib_fc_offset.m';

% ==================== 口径 6：附件5 模板填充规则 ====================
% ✅ 2026-09-13 定死：'corrected_labels'——数据位序不变，表头标签修正。
%    本改动【只改标签、不改任何数值】，全天合计仍是当天 144 槽之和，
%    故既往 Q1–Q4 结果无需重算。
%
% 事实（probe_a5.m / probe_a5b.m 实测，这部分是客观的、不是选择）：
%   result1 计划购电量 144 个标签 = 0:10-0:20, 0:20-0:30, ..., 23:50-0:00+1, 0:00+1-0:10+1
%   即【标准 144 标签删掉 0:00-0:10、末尾补 0:00+1-0:10+1】，整体错位一个槽。
%   佐证：① 同文件【充放电量】用 0:00-4:00…20:00-24:00 与 0:00/24:00 储电量，是自然日；
%         ② result1 末行写 0:00+1-0:10+1，result2 对应列写 0:00-0:10+1，两模板自相矛盾；
%         ③ 原始 sharedStrings 中 0:00-0:10 整条不存在；
%         ④ 题面用「每天0:00 制定」「0:00 和24:00 储电量相同」，均为自然日。
%   判定：模板生成器写成 for i=1..144（应为 0..143）导致的标签 off-by-one。
%   这是客观的标签缺陷，交付时必须显式交代（题面 bug）。
%
% 三个可选取值——【怎么填】是建模/交付决策，本队于 2026-09-13 面选定第 3 个：
% 'positional'        模板第 i 个数据位 ← 本队第 i 个时段（0:00-0:10 起），表头原样保留。
%                     全天购电量 = 当天 144 槽之和，数值自洽；但交出去的表
%                     第一格仍写着 0:10-0:20，与题面「每天0:00 制定」表象相悖。
% 'literal'           按标签字面填：模板第 i 位 ← 本队第 i+1 时段，末位取次日第 1 时段，
%                     使「全天购电量」变成 0:10→次日0:10 的跨日量，
%                     与本文件【充放电量】的自然日口径冲突（已知矛盾，故不选）。
cfg.tplFill = 'corrected_labels';   % 2026-09-13 定死
% 'corrected_labels'  ← 【本次定死】数据位序同 'positional'（第 i 位 ← 第 i 个自然日时段），
%                     但把表头标签由 0:10-0:20 … 23:50-0:00+1, 0:00+1-0:10+1
%                     改写为标准 00:00-00:10 … 23:50-24:00。即【改标签、不改数值】。
%                     理由：① 日申报合计（Excel SUM 第 B..EO 列）仍是当天 144 槽之和，
%                     与【充放电量】【储电量】的自然日口径一致，不引入跨日量；
%                     ② 消除「模板首格是 0:10」这一与题面「每天0:00 制定」相悖的表象；
%                     ③ 与题面「0:00 和 24:00 储电量相同」的自然日语义对齐。
%                     即：该选项同时拿到了 'positional' 的数值自洽与
%                     'literal' 的表头正确，代价是输出模板与原模板表头不同——
%                     此偏离必须在论文中声明（已声明，见下）。
%
% 披露位置（已逐处核实）：
%   ① 论文 §4.2「时间对齐与预报降尺度」【显式披露】：保留模板的工作表和字段
%      结构，将表头改为00:00至00:10开始、23:50至24:00结束，电量仍按真实时段填写；
%   ② 附A 包内 README.md「数据与计算口径」第 2 条【显式披露】：
%      原模板的时间标签整体晚了10分钟，已修正表头，未移动实际电量。
%   · 论文附录C 以「0:00计划 g」表述，与该处理相容，但未单独声明表头修正，
%     故不计入披露处数（如需加强可在附录C 补一句，属可选）。
cfg.tplNote = '附件5 模板标签 off-by-one；2026-09-13 定死为 corrected_labels：数据位序不变、表头改写为 00:00-00:10…23:50-24:00，已在论文 §4.2 与 README 口径第 2 条显式披露';

% ==================== 口径 7：Q2/Q3 信息集 ====================
% ✅ 2026-09-13 定死：'forecast'（日前计划只用决策日前的历史 + 附件3 发布预报）。
%    论文按此执行：实测价不进入主决策；问题四中实测价只用于最终结算。
%    追溯：本值原为占位值，队内于 2026-09-13 当面追认，取值未变，
%    故既往 Q2–Q4 结果无需重算。
%
% 'forecast' 日前计划只能用【决策日前】的历史 + 附件3 的发布预报
%            ⇒ 计划与实际有偏差 ⇒ 紧急购电/调整购电非平凡（5 倍/1.5 倍罚则才有意义）
% 'oracle'   假定已知当天实际负载与光伏 ⇒ 偏差恒为 0、紧急购电恒为 0（退化）
% 提示：若选 'oracle'，Q2 退化为 Q1 重算、5 倍紧急电价完全不起作用，与题目设计相悖；
%       本队于 2026-09-13 当面选定向 'forecast'。
cfg.infoSet = 'forecast';      % 2026-09-13 定死

% ==================== 路径 ====================
cfg.base   = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\CUMCM2026Problems\C题\附件\';
cfg.tpldir = [cfg.base '附件5\'];      % 五个输出模板所在目录
cfg.outdir = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\数据预处理代码\out\';
% 注：曾有 cfg.resdir（结果输出到 code/results/），随导出模块一并移除。
%     结果写到哪里由队内定，不在预处理阶段预设。

if ~isfolder(cfg.outdir)
    mkdir(cfg.outdir);
end
end
