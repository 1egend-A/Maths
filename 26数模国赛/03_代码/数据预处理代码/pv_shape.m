function S = pv_shape(D, cfg)
% PV_SHAPE  从附件2 全年实际光伏统计【日内 10 分钟形状】，供 p0_downscale 使用
%
% 输出 S: 24×6 权重矩阵。S(h,s) = 第 h 小时第 s 个 10 分钟槽的相对权重，
%         每行已归一化到均值 1（即 sum(S(h,:)) = 6），可直接乘小时值。
%
% 构造：
%   对每一天、每一小时，算该小时 6 个槽的相对形状 v_s / mean(v)。
%   只统计【该小时均值 > 阈值】的样本（夜间恒 0 的小时无形状可言，跳过）。
%   对没有有效样本的小时，退化为均匀权重（全 1）。
%
% 目的：把附件3 的【小时】预报降尺度到 10 分钟时，保留真实的光伏爬坡形状，
%       而不是简单阶梯。均值守恒由 p0_downscale 的 renormHourly 强制保证。

P = D.actual.pv;                        % 365×144
S = ones(24, 6);                        % 默认均匀
thr = 5.0;                              % kW，低于此视为夜间/晨昏无效样本
minN = 20;                              % 至少这么多样本才统计形状

% ⚠️ 阈值不能取太小。曾用 thr=1.0：第 5 小时（04:00-05:00）只有少数几天
%    均值刚过 1 kW，比值被噪声主导，统计出 [0.167 0 0 2.323 0 3.510] 这种
%    物理上不可能的形状（该小时本该全天为 0）。取 5 kW 并要求 ≥20 样本后
%    该小时自动退化为均匀权重。

for h = 1:24
    blk = P(:, 6*(h-1)+(1:6));          % 365×6
    hm  = mean(blk, 2);                 % 365×1
    ok  = hm > thr;
    if sum(ok) < minN
        continue;                       % 样本太少，保留均匀权重
    end
    v = blk(ok, :) ./ hm(ok);           % 相对形状 365×6
    w = mean(v, 1);
    w = max(w, 1e-6);                   % 防负/零
    S(h, :) = w / mean(w);              % 归一化到均值 1
end
end
