function qc = q3_config(overrides)
% Q3_CONFIG  问题三专属参数与口径声明（问题三 / 问题四 共用）
%
% 物理参数一律继承 p0_config（本文件不复制、不改写），只追加问题三特有的设定。
% 问题四通过 q4_config.m 调用本函数并把 priceMode 改成 'volatile'，
% 从而保证 Q3 与 Q4 是【同一套模型、同一套代码，只换电价输入】。
%
% ============================================================
%  Q3 口径声明（2026-09-12）
%
%  题目原文依据（问题3 段）：
%    「在每天0:00、6:00、12:00 和18:00 可获得未来24 小时整点的光伏发电功率预报」
%        → 四个信息到达时刻；0:00 定【计划】，6/12/18 定【调整】
%    「计划购电量高于调整购电量的部分，违约电价是交易时刻电价的50%」
%        → 少买的部分按 0.5·p 计
%    「调整购电量高于计划购电量的部分，超出部分的电价是交易时刻电价的1.5 倍」
%        → 多买的部分按 1.5·p 计
%    「总的购电费用包括计划购电费用、紧急购电费用和调整购电量的相关费用」
%        → 总费用 = 三块之和（本文件的成本口径逐字对应这三块）
%    「请分析是否需要引入其他时刻的预报制定调整购电策略」
%        → 用消融实验定量回答，见 t_q3_ablation.m
%
%  ------------------------------------------------------------
%  ★ 单一造价式（本问最容易做错的一条，务必看清）
%
%    cost_t = p_t·dt·[ min(G_t, A_t)              ← 用掉的那部分，按基准价
%                    + 0.5·(G_t − A_t)^+          ← 报多了没用的部分，按 50% 价（违约费）
%                    + 1.5·(A_t − G_t)^+ ]        ← 报少了超出部分，按 150% 价
%
%    该式对 A_t 是【凸的】分段线性函数（斜率 0.5 / 1.5，拐点在 G_t），
%    故可用两条切线约束写进 LP，无需引入 0-1 变量。
%
%    三块拆开恰好对应题面那句话：
%       计划购电费用 = Σ p_t·dt·min(G_t,A_t)        → result3「计划购电量」表的全天购电费
%       调整购电量相关费用 = Σ p_t·dt·[0.5(G−A)^+ + 1.5(A−G)^+]  → 「调整购电量」表的全天购电费
%       紧急购电费用 = Σ 5·p_t·dt·e_t               → 「紧急购电量」表
%
%    【另一种读法及其排除】若把「计划购电费用」理解为「计划量按全额 p 计费、
%    罚金另加」，则总成本为 Σp·G + Σp[0.5(G−A)^+ + 1.5(A−G)^+]，临界分位变成
%    0.25 而非 0.5。本队不采用：题面「违约电价是…的50%」的语义是【该部分按半价
%    结算】，即 min(G,A)+半价差额，而非「全价 + 半价罚金」。二者的差异见
%    t_q3_reading.m 的对照实验。
%
%  ------------------------------------------------------------
%  ★ 报童临界分位（本问的解析内核，四问统一叙事的第三块）
%
%    记 Q_t = 需外购净需求（= 净负荷 + 充电 − 放电），是唯一的随机量。
%    全部临界分位统一为  1 − c_边际 / c_紧急，与问题二的 1 − 1/5 = 0.8 是同一公式。
%
%    (1) 调整量 A_t（给定计划 G_t，在 6/12/18 时刻用新信息决定）：
%        A 的两支边际成本不同——
%          A > G 支：边际成本 1.5p，边际收益 5p·P(Q>A) ⇒ P(Q>A*) = 1 − 1.5/5 = 0.7
%          A < G 支：边际成本 0.5p，边际收益 5p·P(Q>A) ⇒ P(Q>A*) = 1 − 0.5/5 = 0.9
%        两支合并（拐点取角点），得到闭式
%            **A*_t = min( max(G_t, Q_(0.7)), Q_(0.9) )**
%        即「把 70 分位夹在计划与 90 分位之间」。
%
%    (2) 计划量 G_t（在 0:00 制定）：分区域看边际条件
%          · 调整【不起作用】的时段（A=G，占多数）：∂C/∂G = p·[1 − 5·P(Q>G)] = 0
%            ⇒ **P(Q>G*) = 0.2，即 G* = Q_(0.8)** —— 与问题二【完全同一个分位】，
%            因为此时本问的计划问题与问题二同构（计划量按计划价结算、缺口按 5p 紧急购电）。
%          · 调整【起作用】的时段：A>G 侧 ∂C/∂G = −0.5p < 0（该调高），
%            A<G 侧 ∂C/∂G = +0.5p > 0（该调低），把 G 拉向 A 的分布中心。
%        两者合起来，最优 qPlan 略低于 0.8。实测（t_q3_planquant.m，60 天扫描）：
%            qPlan   0.40    0.50    0.60    0.70    0.80    0.90
%            相对最优 +1.43% +0.77% +0.32%   0%    +0.013% +0.94%
%        代价曲线在 [0.70, 0.80] 内几乎完全平坦（0.70 与 0.80 相差 0.013%）。
%        **本模型取 qPlan = 0.8**：它是闭式可证的（与问题二同源），且与经验最优
%        仅差 0.013%。取 0.8 还带来一个额外好处——问题二与本问的【计划分位相同】，
%        于是 Q2 与 Q3 的差异被干净地隔离为「有无调整机制」这一项，可直接对照。
%
%    （若取 qPlan = 0.5，即「计划偏离调整的罚则上下对称 ⇒ 取中位数」这一直觉，
%      实测会多花 0.77%。该直觉忽略了 5 倍紧急购电对计划量的对冲需求。）
%
%  口径 2  日末 SOC = 【固定 6000】(fixed6000)            ← 本条为决策
%      每日 S_0 = S_144 = 6000，与问题一/问题二完全一致（见 q2_config.m 的理由）。
%      问题三逐日电价仍然相同，故该口径的代价依然很小；其实测见 t_q3_term_policy.m。
%      问题四逐日电价不同，该口径的代价会显著放大——见 t_q4_term_policy.m。
%
%  口径 3  调整量结算粒度 = 【逐 10 分钟】(slot)           ← 本条为决策
%      逐时段比 G_t 与 A_t。另一读法「按全天总量比」的敏感性见 t_q3_granularity.m。
%
%  口径 6  附件5 模板填充 = 【positional】，与问题二一致，保证 result2/result3 自洽。
%
%  口径 7  信息集 = 【官方预报】(forecast)
%      问题三题面明确给出附件3，故光伏用附件3 的官方预报；负载【无官方预报】，
%      仍用自预测（与问题二同一套 blend 预测器），这构成本问调整能力的天然上限。
%      与问题二（严格字面，不用附件3）形成「有/无官方预报」的受控对照。
%
%  口径 1/4/5 直接继承 p0_config（交流侧计量 / 右端点时段 / 附件3 偏移 = +1）。
% ============================================================
%
% 用法：
%   qc = q3_config();                          % 默认：附件1 固定电价
%   qc = q3_config(struct('priceMode','volatile'));   % 问题四：附件4 逐日电价

P0DIR = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\数据预处理代码';
if isempty(which('p0_config')), addpath(P0DIR); end

cfg = p0_config();

% ---------- 继承并复述关键物理参数（只读，勿在此改动）----------
qc.eta   = cfg.eta;
qc.P_max = cfg.P_max;
qc.S_min = cfg.S_min;
qc.S_max = cfg.S_max;
qc.S0    = cfg.S0;        % 6000
qc.S_end = 6000;          % 口径 2：日末固定 6000
qc.termPolicy = 'close';  % 'close' = 日末固定 S_end（默认）| 'free' = 末槽只受上下限（对照用）
                          % 对照见 t_q3_term_policy.m；q3_lp.m 按此字段决定末槽是否钉死
qc.dt    = cfg.dt;
qc.effConv = cfg.effConv;
qc.fcOffset = cfg.fcOffset;
qc.fcIssHours = cfg.fcIssHours;   % [0 6 12 18]

% ---------- 求解区间 ----------
% 依据：附件5 result3.xlsx 模板的日期表与 result2 同构，均为 2025-02-01 … 12-31。
qc.dayIdx    = 32:365;
qc.dateFirst = datetime(2025,2,1);
qc.dateLast  = datetime(2025,12,31);

% ---------- 口径 7：信息集 ----------
qc.infoSet = 'forecast';     % 用附件3 官方光伏预报 + 自预测负载

% ---------- 电价来源 ----------
% 'fixed'    ：附件1 的 144 段报价，逐日相同（问题三）
% 'volatile' ：附件4 的 365×144 实测电价，逐日逐时段不同（问题四）
qc.priceMode = 'fixed';
qc.priceNote = 'fixed=附件1典型日报价(逐日相同); volatile=附件4逐日实测电价';

% ---------- 罚则系数（题面直接给出）----------
qc.kEm    = 5;    % 紧急购电电价倍数
qc.kOver  = 1.5;  % 调整量高于计划量：超出部分电价倍数
qc.kUnder = 0.5;  % 计划量高于调整量：违约部分电价倍数

% ---------- 报童临界分位（由罚则系数导出，勿随意改）----------
qc.qPlan   = 1 - 1/qc.kEm;                 % 计划量 = 1 − 1/5 = 0.8（与问题二同源，见上）
qc.qAdjLo  = 1 - qc.kOver /qc.kEm;         % 调整量下侧 = 1 − 1.5/5 = 0.7
qc.qAdjHi  = 1 - qc.kUnder/qc.kEm;         % 调整量上侧 = 1 − 0.5/5 = 0.9
assert(abs(qc.qPlan - 0.8) < 1e-12 && abs(qc.qAdjLo - 0.7) < 1e-12 && abs(qc.qAdjHi - 0.9) < 1e-12);

% ---------- 滚动阶段开关（供消融实验用）----------
% 索引 1..4 对应发布时刻 [0 6 12 18]。
%   第 1 位 = 0:00 制定【计划】（必开，关掉就退化成"不购电"）
%   第 2..4 位 = 6/12/18 是否【执行调整】
% 消融实验 A0 = [1 0 0 0]（只用 0:00），A3 = [1 1 1 1]（全用）。
qc.useStages = [true true true true];

% ---------- 预测方法 ----------
% 负载：与问题二同一套（问题三没有负载预报可用），保证与问题二可比。
qc.loadMethod = 'blend';     % 0.5*上周同日 + 0.5*近4周同星期几均值
% 光伏：用附件3 官方预报（本问题面给出）。qc.pvSelfMethod 仅在消融对照中用于
% 「不用附件3、改用自预测」的分支，见 t_q3_ablation.m 的 A0' 组。
qc.pvSource     = 'a3';      % 'a3' = 附件3 官方预报（默认）
                             % 'self'   = 不用附件3，改用自预测（消融对照）
                             % 'blend3' = w·附件3 + (1−w)·自预测（消融对照）
qc.pvBlendW     = 0.15;      % blend3 的附件3 权重（预处理阶段实测的最优线性权重）
qc.pvSelfMethod = 'mean7';   % 自预测备选（近 7 日同时刻均值）

% ---------- 降尺度（小时 → 10 分钟）----------
% 附件3 是整点粒度，决策是 10 分钟粒度，必须降尺度。
% p0_downscale 末尾有硬 assert 保证逐小时均值严格守恒。
qc.dsMethod = 'shape';       % 'stair' | 'linear' | 'shape'
% t_q3_downscale.m 对比 linear / shape / stair 三种方法的费用差异。

% ---------- 情景集（不确定性描述）----------
% 用【同一发布时刻的附件3 预报】在近 nScen 天留下的净负荷残差作为经验分布。
% 注意：误差源是附件3 的预报误差 + 自预测负载的误差之和，与问题二不同。
qc.nScen = 30;

% ---------- LP 中购电变量的计价系数（敏感性参数，默认 1）----------
% 购电变量不进入 SOC 递推，其取值只影响 LP 对「购电 vs 用储能搬移」的权衡。
% 1.0 = 基准交易电价（与问题二完全一致的写法）。敏感性见 t_q3_lpcoef.m。
qc.lpPriceCoef = 1.0;

% ---------- 口径 6：模板填充 ----------
qc.tplFill = 'positional';
qc.tplFile = [cfg.tpldir 'result3.xlsx'];

% ---------- 输出路径 ----------
qc.outdir  = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\问题三\out\';
qc.resFile = [qc.outdir 'result3.xlsx'];
qc.q3dir   = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\问题三\code\';

% ---------- 求解器开关 ----------
qc.lpAlgo  = 'dual-simplex';
qc.verbose = true;

% ---------- 调用者可覆盖（问题四用这个入口）----------
if nargin >= 1 && ~isempty(overrides)
    fn = fieldnames(overrides);
    for i = 1:numel(fn)
        qc.(fn{i}) = overrides.(fn{i});
    end
end
end
