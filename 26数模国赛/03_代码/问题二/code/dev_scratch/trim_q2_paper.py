def main():
    s = io.open(MD, encoding='utf-8').read()
    bad = 0
    for i, (a, b) in enumerate(SUBS, 1):
        n = s.count(a)
        if n != 1:
            print('  [%2d] MISS/AMBIG n=%d :: %s' % (i, n, a[:50].replace('\n', '|')))
            bad += 1
            continue
        s = s.replace(a, b)
    if bad:
        print('有 %d 条未命中，未写盘（避免半成品）' % bad)
        return 1
    io.open(MD, 'w', encoding='utf-8', newline='\n').write(s)
    print('已应用 %d 条精简' % len(SUBS))
    return 0


if __name__ == '__main__':
    sys.exit(main())
