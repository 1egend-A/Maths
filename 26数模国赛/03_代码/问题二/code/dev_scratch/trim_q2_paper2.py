def main():
    s = io.open(MD, encoding='utf-8').read()
    bad = 0
    for i, (a, b) in enumerate(SUBS, 1):
        n = s.count(a)
        if n != 1:
            print('  [%d] MISS/AMBIG n=%d :: %s' % (i, n, a[:50].replace('\n', '|')))
            bad += 1
            continue
        s = s.replace(a, b)
