function qc = q2_config()
% Q2_CONFIG  问题二专属参数与口径声明
%
% 物理参数一律继承 p0_config（本文件不复制、不改写），只追加问题二特有的设定。
%
% ============================================================
%  Q2 口径声明（2026-09-12 定，替代 p0_config 中的占位值）
%
%  题目原文依据（问题2 段）：
%    「每天的电价相同」                    → 电价 = 附件1 的 144 段报价，逐日相同
%    「根据附件1 中的电价和附件2 中的数据」 → 信息集只含 附件1 + 附件2
%    「其他时间段的购电费用均按计划购电量计算」→ 计划电量按计划数结算，不退不补
%    「如果低于负载，需向外网紧急购电，其电价是交易时刻电价的5倍」
%
%  据此，问题二的四条口径取值为：
%
%  口径 7  信息集 = 【严格字面】(strict-literal)      ← 本条为决策
%      只用附件1 + 附件2。附件3 在问题2 的题面里【未被引用】（附件3 只在
%      问题3 的题面出现），故不采用其官方光伏预报。代价是负载与光伏都必须
%      自行预测；好处是模型与题面信息结构严格对应，且与问题3 形成
%      「有/无官方预报」的天然对照。
%      （附件3 也【没有负载预报】，即便想用在负载侧也无数据可用。）
%
%  口径 2  日末 SOC = 【固定 6000】(fixed6000)          ← 本条为决策
%      每日 0:00 与 24:00 储电量均为 6000 kWh，即 S_0 = S_144 = 6000。
%      理由：① 与问题一完全一致（问题一题面明确要求「0:00 和24:00 的储电量
%      相同」，且队友 Q1 已按 S_0=S_144=6000 落地）；
%      ② 逐日电价【完全相同】、逐日净负荷分布近似平稳 ⇒ 跨日搬运储能的边际
%      价值为零，日末回到起点近乎不失最优性（有无代价见 t_q2_term_policy.m
%      的实测对照）；③ 若不闭环，日末 SOC 在最优解集内不唯一，结果不可复现；
%      ④ 问题二区间自 2025-02-01 起，而题面只给了 2025-01-01 0:00 的 6000 kWh
%      —— 闭环使每日计划自洽，无需先去解 1 月来倒推起始 SOC。
%
%  口径 6  附件5 模板填充 = 【positional】               ← 本条为决策
%      模板标签整体错位一个槽（probe_a5.m 已实证：0:00-0:10 整条标签不存在，
%      末尾多出 0:00-0:10+1）。处理办法：**不改模板标签**，模板第 i 个数据位
%      直接写本队第 i 个时段（0:00-0:10 起）。与队友 Q1 的处理方式一致，
%      保证 result1/result2/result3 三份交付物内部自洽。论文中须显式交代。
%
%  口径 3  结算粒度：问题二【不需要】本条。题面已直接规定「其他时间段的购电
%      费用均按计划购电量计算」，不存在调整电量，故无粒度选择问题；
%      本条只在问题三（计划 vs 调整）才有意义。
%
%  口径 1/4/5 直接继承 p0_config（交流侧计量 / 右端点时段 / 附件3 偏移），
%      问题二不使用附件3，故口径 5 在本问不生效。
% ============================================================

% 依赖预处理代码目录（p0_config.m / out\data.mat 都在那里）。
% 放在函数内是为了本问所有脚本都能单独运行，不要求调用者先手工 addpath。
P0DIR = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\数据预处理代码';
if isempty(which('p0_config')), addpath(P0DIR); end

cfg = p0_config();

% ---------- 继承并复述关键物理参数（只读，勿在此改动）----------
qc.eta   = cfg.eta;
qc.P_max = cfg.P_max;
qc.S_min = cfg.S_min;
qc.S_max = cfg.S_max;
qc.S0    = cfg.S0;        % 6000
qc.S_end = 6000;          % 口径 2：日末固定 6000
qc.dt    = cfg.dt;
qc.effConv = cfg.effConv;

% ---------- 问题二求解区间 ----------
% 依据：附件5 result2.xlsx 模板的 计划购电量 表恰有 334 个日期行，
%       首行 2025-02-01、末行 2025-12-31 ⇒ 题面隐含区间即 2/1–12/31。
qc.dayIdx   = 32:365;             % 对应 data.mat 中 actual 的行号
qc.dateFirst= datetime(2025,2,1);
qc.dateLast = datetime(2025,12,31);

% ---------- 口径 7：信息集 ----------
qc.infoSet = 'strict-literal';

% ---------- 预测方法（由 t_forecast_backtest.m 回测选定）----------
% 负载：blend = 0.5*lag7 + 0.5*mean28w   MAPE 3.93%（次优 lag7 4.13%）
%       权重扫描 w∈[0.4,0.7] 内 MAPE 变化 < 0.08 个百分点 ⇒ 取等权 0.5 更稳
% 光伏：mean7 = 近 7 日同时刻均值        RMSE 303.86 / 白天RMSE 430.19（最优）
qc.loadMethod = 'blend';   % 0.5*上周同日 + 0.5*近4周同星期几均值
qc.pvMethod   = 'mean7';   % 近 7 日同时刻均值
% 注：负载有强「星期」周期（lag7 远胜 lag1 与 mean7），光伏受天气驱动、无星期
%     结构（mean7 胜 lag7）。两者最优方法不同，故不共用同一套预测器。

% ---------- 情景集（不确定性描述）----------
% 用「同一预测方法在近 nScen 天留下的净负荷预测残差」作为经验分布样本。
% 净负荷 N = L - PV：负载与光伏在约束与费用中【只以差值出现】，故随机性
% 完全由净负荷承载（见 q2_solve.m 顶部说明）。
qc.nScen   = 30;                  % 残差样本数（近 30 天）

% ---------- 口径 6：模板填充 ----------
qc.tplFill = 'positional';
qc.tplFile = [cfg.tpldir 'result2.xlsx'];

% ---------- 输出路径 ----------
qc.outdir = 'D:\HuaweiMoveData\Users\26313\Desktop\2026数模国赛\问题二\out\';
% 默认【不覆盖】附件5 原模板：结果另存为 out\result2.xlsx。
% 是否用结果覆盖交付模板，属队内约定，见 p0_config 的路径注记。
qc.resFile = [qc.outdir 'result2.xlsx'];

% ---------- 求解器开关 ----------
qc.lpAlgo  = 'dual-simplex';
qc.verbose = true;
end
